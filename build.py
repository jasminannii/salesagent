#!/usr/bin/env python3
"""Build the standalone landing page.

Reads the design source (src/landingpage.dc.html) and writes index.html,
a single static page that runs anywhere (e.g. GitHub Pages) with the small
runtime in runtime/dc-lite.js.

Usage:  python3 build.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src" / "landingpage.dc.html"
RUNTIME = ROOT / "runtime" / "dc-lite.js"
OUT = ROOT / "index.html"

src = SRC.read_text(encoding="utf-8")

title = re.search(r"<title>(.*?)</title>", src, re.S).group(1).strip()
xdc = re.search(r"<x-dc>(.*)</x-dc>", src, re.S).group(1)
helmet = re.search(r"<helmet>(.*?)</helmet>", xdc, re.S).group(1)
body_tpl = re.sub(r"<helmet>.*?</helmet>", "", xdc, count=1, flags=re.S).strip()

script_tag = re.search(r'<script type="text/x-dc"[^>]*data-props=\'(.*?)\'[^>]*>(.*?)</script>', src, re.S)
props_json = json.loads(script_tag.group(1).replace("&amp;", "&").replace("&#39;", "'"))
logic = script_tag.group(2).strip()
defaults = {k: v.get("default") for k, v in props_json.items() if not k.startswith("$") and isinstance(v, dict)}

runtime = RUNTIME.read_text(encoding="utf-8")

html = f"""<!doctype html>
<html lang="de">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="brayyn – dein KI-Sales-Agent: Anrufliste, Dialer, Lead-Recherche, Pitch und Live-Coaching. Gebaut für Vertriebsteams im DACH-Raum.">
{helmet.strip()}
</head>
<body>
<!-- Generated by build.py from src/landingpage.dc.html – edit the source, then rebuild. -->
<div id="app"></div>
<template id="dc-template">
{body_tpl}
</template>
<script>
{runtime}
</script>
<script>
{logic}
DCLite.mount(document.getElementById('app'), document.getElementById('dc-template'), Component, {json.dumps(defaults)});
</script>
</body>
</html>
"""

OUT.write_text(html, encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({len(html) // 1024} KB)")
